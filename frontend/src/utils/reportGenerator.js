import { redactSensitiveData, computeEvidenceHash } from './privacy';

const OFFICIAL_DISCLAIMER = "LEGAL DISCLAIMER: This incident dossier is generated by BankShield AI, an automated cybersecurity intelligence tool, for preliminary assessment and cyber fraud incident preservation purposes. This document is NOT an official confirmation, verification, or statement issued by any scheduled banking institution or government authority. For legal or financial dispute resolution, contact your bank's nodal officer and register a formal Zero FIR at your local police station or through cybercrime.gov.in (Helpline: 1930).";

/**
 * Build structured forensic incident report object with evidence hash.
 */
export async function buildIncidentReport(analysisResult, rawMessage, sender = 'Not Specified') {
  const timestamp = new Date().toISOString();
  const redactedMessage = redactSensitiveData(rawMessage);
  
  const baseReport = {
    report_title: "BankShield AI Forensic Incident Report",
    generated_at: timestamp,
    incident_id: "BS-INC-" + Date.now(),
    redacted_message: redactedMessage,
    sender_identifier: sender,
    risk_assessment: {
      risk_score: analysisResult.risk_score,
      verdict: analysisResult.verdict,
      scam_classification: analysisResult.scam_type
    },
    detected_indicators: (analysisResult.warnings || []).map(w => ({
      indicator_type: w.type,
      evidence_text: w.text
    })),
    highlighted_keywords: analysisResult.highlights || [],
    recommended_actions: analysisResult.advice || [],
    telecom_dlt_verification: {
      is_authentic_header: analysisResult.sender_details?.is_authentic_header || false,
      sender_type: analysisResult.sender_details?.sender_type || "Unverified",
      operator: analysisResult.sender_details?.telecom_operator || "Unknown",
      circle: analysisResult.location_details?.telecom_circle || "National Route"
    },
    national_helplines: {
      cyber_crime_helpline: "1930",
      emergency_police: "112",
      portal_url: "https://cybercrime.gov.in"
    },
    disclaimer: OFFICIAL_DISCLAIMER
  };

  // Compute cryptographic SHA-256 evidence hash of the report
  const reportString = JSON.stringify(baseReport);
  const evidenceHash = await computeEvidenceHash(reportString);

  return {
    ...baseReport,
    evidence_hash_sha256: evidenceHash
  };
}

/**
 * Trigger downloadable JSON forensic report.
 */
export async function downloadJsonReport(analysisResult, rawMessage, sender) {
  const report = await buildIncidentReport(analysisResult, rawMessage, sender);
  const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(report, null, 2));
  const downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute("href", dataStr);
  downloadAnchor.setAttribute("download", `BankShield_Incident_${report.incident_id}.json`);
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
  return report;
}

